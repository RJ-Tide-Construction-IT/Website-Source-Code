        <h3>Summary / Objective</h3>
        <p>Craftsman 2 performs a variety of carpenter and/or concrete finisher tasks involving physical
           labor at small and large concrete construction projects. The position may operate a variety of
           hand and power tools, clean and prepare sites, dig trenches, set braces to support the sides of
           excavations, erect scaffolding, clean up rubble and debris, and remove waste materials. The
           position may assist or lead other craftsman tier workers.</p>

        <h3>Essential Functions</h3>
        <p>Reasonable accommodations may be made to enable individuals with disabilities to perform the
           essential functions.</p>
        <ul>
            <li>Must be able to perform most of the Craftsman 1 Essential Functions.</li>
            <li>Place concrete in place with the operation of concrete buggy.</li>
            <li>Perform materials handling with the operation of skid loader.</li>
            <li>Loads and unloads trucks. Qualified to operate telehandler to haul and hoist materials.</li>
            <li>Prepare the layout of the project by setting up laser off benchmark for grade points.</li>
            <li>Estimate height, width, length, and other proportions. Understand measurements in tenths and inches.</li>
            <li>Basic understanding of structural and rebar blueprints reading.</li>
            <li>Can perform job site layout from established points.</li>
            <li>Ability to set Symons forms in place and on-grade forms.</li>
            <li>Build wood forms for pouring concrete.</li>
            <li>Ability to build wall bracing and use turn buckles.</li>
            <li>Work on ladders, scaffolding, and machinery.</li>
            <li>Check work in process to verify it meets plans and specifications. Use transit, smart level, total station, or other surveying equipment to double check everything is level and secure.</li>
            <li>Erect scaffolding.</li>
            <li>Awareness of material and fasteners supply needs on site and keep supervisor informed of restock needs before crew runs out.</li>
            <li>Set anchor bolts, steel plates, door sills and other embeds.</li>
            <li>Owns the proper tools for the task being assigned and keeps them on their tool belt.</li>
            <li>Owns mag, wood, and steel trowels along with edger and margin trowel.</li>
            <li>Ability to roll curbs, and perform edging work correctly.</li>
            <li>Qualified to operate all concrete saws.</li>
            <li>Can operate a walk-behind power trowel.</li>
            <li>Capable of finishing exterior (broom finish) flatwork.</li>
            <li>Pre-plans tool needs after being given work directions for the day.</li>
            <li>Qualified to operate a mini-excavator.</li>
        </ul>

