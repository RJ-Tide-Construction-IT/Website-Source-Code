           inclement weather, heat, humidity, cold, and exposure to dust and concrete.</p>

        <h3>Physical Demands</h3>
        <p>The position lifts heavy objects, walks, and stands for long periods of time and performs
           strenuous physical labor under adverse field conditions. The employee lifts, pushes, pulls or
           carries objects, uses abdominal and lower back muscles to provide support over time without
           fatigue, and effectively walks, climbs, or moves objects. The position requires good manual
           dexterity (hand, hand with arm, two hands) and multi-limb coordination. The position requires
           the ability to quickly move arms and legs. The employee must have excellent stamina.</p>

        <h3>Expected Hours of Work</h3>
