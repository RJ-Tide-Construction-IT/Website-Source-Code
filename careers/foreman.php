        <h3>Summary / Objective</h3>
        <p>RJ Tide&rsquo;s Foremen provide the knowledge, skills and experience required to lead the
           day-to-day field operations of task order and/or commercial construction projects that RJ Tide
           undertakes. RJ Tide&rsquo;s foremen are responsible for leading production aspects of the work
           and are accountable for producing quality work constructed consistent with the standards set
           forth by the project&rsquo;s Superintendent; for performing the work in a timely and cost
           effective manner; and for maintaining a work environment that is safe and continuously kept
           clean and orderly. Moreover, RJ Tide&rsquo;s foremen are the forward face of RJ Tide and are
           responsible for establishing a professional work environment that includes fostering a positive
           atmosphere, promoting proactive and effective communication, facilitating problem solving, and
           minimizing and resolving conflict in a constructive manner. The primary focus of RJ Tide&rsquo;s
           Foremen is to provide the leadership skills necessary to accomplish the work and manage the
           day-to-day issues of a small self-performed workforce under the direction of the Superintendent.</p>

        <h3>Essential Functions</h3>
        <p>Reasonable accommodations may be made to enable individuals with disabilities to perform the
           essential functions.</p>
        <ul>
            <li>Must be able to perform most of the Craftsman 2 Essential Functions.</li>
            <li>Ability to run a 3-4 man crew.</li>
            <li>Has obtained ACI Certified Tech status.</li>
            <li>Has obtained ACI Certified Finisher status.</li>
            <li>Ability to create working schedule for workers.</li>
            <li>Ability to set up GPS / total station for layout and work.</li>
            <li>Qualified to run all equipment and perform minor maintenance work on them.</li>
            <li>Ability to measure strengths and weaknesses of workers.</li>
            <li>Uses logic and reasoning to identify the strengths and weaknesses of alternative solutions, conclusions or approaches to problems.</li>
            <li>Identifies complex problems and reviews related information to develop and evaluate options and implement solutions.</li>
            <li>Assign appropriate tasks to workers.</li>
            <li>Ensure that work is always in good progress.</li>
            <li>Keep Superintendent updated on project development.</li>
            <li>Make sure that work is completed on or before deadlines.</li>
            <li>Ensure that safety of workers is guaranteed at all times.</li>
        </ul>

