        <h3>Summary / Objective</h3>
        <p>RJ Tide&rsquo;s Superintendents provide the knowledge, skills and experience required to manage
           the day-to-day field operations of task order and/or larger lump-sum institutional and/or
           commercial construction projects that RJ Tide undertakes. RJ Tide&rsquo;s Superintendents are
           responsible for the production aspects of the work and are accountable for producing quality
           work constructed consistent with the standards set forth in the project&rsquo;s contract
           documents; for performing the work in a timely and cost effective manner; and for maintaining a
           work environment that is safe and continuously kept clean and orderly. The primary focus of RJ
           Tide&rsquo;s Superintendent is to provide the managerial and leadership skills necessary to
           accomplish the work by means of subcontractors and to manage the day-to-day issues of a small
           self-performed workforce.</p>

        <h3>Essential Functions</h3>
        <p>Reasonable accommodations may be made to enable individuals with disabilities to perform the
           essential functions.</p>
        <ul>
            <li>Managing the day-to-day field activities to ensure that the project milestone dates and overall schedule completion date is met.</li>
            <li>Creating short-interval look-ahead project schedules that make sure upcoming events are communicated, tracked and proactively attended to, and creating and maintaining a culture that values safety, health and cleanliness.</li>
            <li>Managing and coordinating the work to ensure it is constructed in an orderly and deliberate manner consistent with the standard of care set forth in the contract documents.</li>
            <li>Establishing and maintaining all dimensional controls for the project, including the use of third party survey and layout personnel when appropriate.</li>
            <li>Verifying that all work is installed in a workmanlike manner (i.e., plumb, level, straight, etc.).</li>
            <li>Managing and looking ahead no less than two weeks to proactively identify issues that could lead to problems and facilitate solutions.</li>
            <li>Obtaining all inspections and ensuring the quality aspects of the physical work are fully documented.</li>
            <li>Ensuring all aspects of the project are compliant with all contract terms and legal requirements that govern the project and the community in which it takes place.</li>
            <li>Administering client specific programs, such as CQC, Safety, and Environmental Stewardship.</li>
            <li>Conducting and/or attending pre-construction, progress and other project and staff meetings.</li>
            <li>Meeting with client representatives on a regular basis to discuss project status, proactively identify and resolve problems, and keep the client informed.</li>
            <li>Managing self-performed activities to ensure work is performed within the established project budget.</li>
            <li>Managing changes in project scope to ensure the most contemporary contract documents are used at all times to prevent avoidable rework.</li>
            <li>Administering contracts, subcontracts, purchase orders and other agreements to ensure scope, terms and conditions are consistently met.</li>
            <li>Managing the punch list and project closeout process to assure timely completion.</li>
            <li>Maintaining daily paperwork such as timecards, field reports, schedule updates and email correspondence.</li>
            <li>Providing timely and cordial interaction with supporting work groups, such as accounting, HR and management.</li>
            <li>Directing and managing the workloads of supporting staff, including training, mentoring and follow up.</li>
            <li>Ensures that proper safety and incident reporting procedures are followed. Brings problems to the attention of the Safety Director or HR manager.</li>
        </ul>

        <h3>Competencies</h3>
