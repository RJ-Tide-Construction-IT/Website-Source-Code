        <h3>Work Environment</h3>
        <p>While performing the duties of this job, the employee is frequently exposed to fumes or airborne
           particles, moving mechanical parts and vibration. The employee is occasionally exposed to a
           variety of extreme conditions at construction job sites. The noise level in the work environment
           and job sites can be loud. The position regularly works near moving mechanical parts and in
           outside conditions that include inclement weather, heat and humidity, and exposure to dust.</p>

        <h3>Physical Demands</h3>
        <p>The position lifts heavy objects, walks and stands for long periods of time and performs
           strenuous physical labor under adverse field conditions. The position requires good manual
           dexterity and multi-limb coordination, and the employee must have excellent stamina.</p>

        <h3>Position Type / Expected Hours of Work</h3>
        <p>This is a full-time position. Days and hours of work are Monday through Friday, 7:00 a.m. to
           4:00 p.m., 45 hours per week, plus overtime as job conditions require. This position frequently
           requires long hours and potential weekend work.</p>

        <h3>Travel</h3>
        <p>Travel is primarily local during the business day, although some out-of-area and overnight
           travel may be expected.</p>

        <h3>Required Education and Experience</h3>
        <ul>
            <li>AS degree in Construction Management or similar, or a Journeyman status in a building trade, AND no less than 5 years of progressive responsibility supervising construction.</li>
            <li>Minimum 7 years&rsquo; experience in the construction industry with a commercial and/or institutional general contractor engaged in general building and civil construction.</li>
            <li>A working knowledge of civil, architectural, mechanical and electrical work.</li>
            <li>The ability to effectively communicate both in written and spoken English.</li>
            <li>The ability to read and understand blueprint drawings.</li>
        </ul>

        <h3>Preferred Education and Experience</h3>
