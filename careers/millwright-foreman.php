        <h3>Summary / Objective</h3>
        <p>RJ Tide&rsquo;s Millwright Foremen provide the knowledge, skills and experience required to lead
           the day-to-day field operations of millwright crews on agricultural and industrial projects.
           RJ Tide&rsquo;s millwright foremen are responsible for leading production aspects of the work
           and are accountable for producing quality work constructed consistent with the standards set
           forth by the project&rsquo;s Superintendent; for performing the work in a timely and cost
           effective manner; and for maintaining a work environment that is safe and continuously kept
           clean and orderly. The primary focus of RJ Tide&rsquo;s Millwright Foreman is to provide the
           leadership skills necessary to accomplish the work and manage the day-to-day issues of a small
           self-performed millwright crew under the direction of the Millwright Superintendent.</p>

        <h3>Essential Functions</h3>
        <p>Reasonable accommodations may be made to enable individuals with disabilities to perform the
           essential functions.</p>
        <ul>
            <li>Must be able to perform most of the Millwright 2 Essential Functions.</li>
            <li>Ability to run a 3&ndash;4 man millwright crew.</li>
            <li>Ability to create working schedules for crew members.</li>
            <li>Qualified to run all Company equipment and perform minor maintenance work on them.</li>
            <li>Rig for crane, safety tie off points, and hoisting materials.</li>
            <li>Coordinate erection of structural steel, square bins, towers, and catwalks.</li>
            <li>Ability to measure strengths and weaknesses of crew members.</li>
            <li>Assign appropriate tasks to crew members.</li>
            <li>Ensure that work is always in good progress.</li>
            <li>Keep Superintendent updated on project development.</li>
            <li>Make sure that work is completed on or before deadlines.</li>
            <li>Ensure that safety of crew members is guaranteed at all times.</li>
            <li>Ensures that proper safety and incident reporting procedures are followed. Brings problems to the attention of the Millwright Superintendent, Safety Director, or HR manager.</li>
        </ul>

