        <h3>Summary / Objective</h3>
        <p>The Millwright Level 2 is responsible for installing, maintaining, troubleshooting, and
           repairing mechanical machinery and equipment in accordance with safety, preventative maintenance
           programs, and standard procedures. A Level 2 millwright is expected to work semi-independently
           and demonstrate intermediate proficiency in mechanical repair and alignment.</p>

        <h3>Essential Functions</h3>
        <ul>
            <li>Able to perform all the Essential Functions of the Millwright 1 position at a satisfactory level.</li>
            <li>Replace drive components such as gear boxes, motors, sheaves, V-belts, head shafts, bearings, main drive sprockets, head/tail pulleys, and lagging.</li>
            <li>Splicing, tensioning and tracking leg &amp; conveyor belts.</li>
            <li>Repair distributors and distributor adjustment problems.</li>
            <li>Patch and/or reline spouts and components.</li>
            <li>Perform intermediate to advanced troubleshooting and diagnostics on mechanical equipment.</li>
            <li>Erection of structural steel, square bins, towers and catwalks.</li>
            <li>Equipment installation (mixers, scalpers, roller mills, etc.).</li>
            <li>Read and interpret blueprints, diagrams, schematic drawings, and manufacturer manuals to determine work procedures.</li>
            <li>Use precision measuring tools (e.g., micrometers, calipers, dial indicators) to align and adjust parts to specifications.</li>
            <li>More advanced welding skills; weld galvanized metals, stainless, and thin metal.</li>
            <li>Rig for crane, safety tie off points, and hoisting materials.</li>
            <li>Able to safely operate powered industrial equipment, including signals.</li>
            <li>Ensure all work is completed in compliance with company safety policies and procedures.</li>
            <li>Learn from previous mistakes and actively work to avoid repeating them.</li>
            <li>Apply growing knowledge and skills to successfully perform assigned duties.</li>
        </ul>

        <h3>Required Education and Experience</h3>
        <p>At least 2 years of experience in an industrial or manufacturing setting performing millwright work.</p>

        <h3>Preferred Education and Experience</h3>
        <ul>
            <li>3&ndash;5 years of experience in an industrial or manufacturing setting.</li>
            <li>Strong knowledge of mechanical systems, hydraulics, pneumatics, and power transmission equipment.</li>
            <li>Intermediate knowledge of welding, fabrication, and rigging.</li>
            <li>Ability to work with minimal supervision.</li>
            <li>Strong problem-solving skills and attention to detail.</li>
            <li>Physically fit and able to work in confined spaces, at heights, and lift heavy equipment.</li>
            <li>Willingness to work overtime, shifts, or on-call as needed.</li>
        </ul>

