        <h3>Essential Characteristics</h3>
        <ul>
            <li>Well-organized</li>
            <li>Detail-oriented</li>
            <li>Self-motivated</li>
            <li>Eager to learn</li>
            <li>Communicates clearly and honestly</li>
        </ul>

        <h3>Tasks Assigned to Project Engineer</h3>
        <p>The Project Engineer supports the Project Manager / Estimator across the life of a project,
           from early takeoff work through closeout, with a focus on document control and field
           coordination.</p>

        <h4>Estimating Support</h4>
        <ul>
            <li>Review plans &amp; specs to identify project takeoff requirements.</li>
            <li>Assist with quantity takeoffs using On Screen Takeoff (OST).</li>
            <li>Help prepare takeoff summary spreadsheets.</li>
            <li>Support the Project Manager / Estimator in finalizing estimates.</li>
        </ul>

        <h4>Project Startup</h4>
        <ul>
            <li>Assist with contract estimate &amp; cost coded budget upload.</li>
            <li>Help set up field files and hand off documentation to the field team.</li>
            <li>Assist with safety precon review preparation.</li>
        </ul>

        <h4>Field Coordination</h4>
        <ul>
            <li>Maintain construction document control and revisions.</li>
            <li>Track and distribute submittals.</li>
            <li>Maintain project contact lists.</li>
            <li>Assist with material buyout sheets and delivery coordination.</li>
            <li>Track RFIs and follow up to keep them moving.</li>
            <li>Support QAQC processes in the field.</li>
            <li>Help manage project correspondence.</li>
        </ul>

        <h4>Budget Support</h4>
        <ul>
            <li>Assist with monthly pay app preparation and work-in-place verification.</li>
            <li>Support monthly cost projections and forecasts.</li>
            <li>Help review labor hours &amp; as-built production with the field.</li>
        </ul>

        <h3>Required Education and Experience</h3>
        <p>N/A, open to candidates early in their construction management or engineering career.</p>

        <h3>Preferred Education and Experience</h3>
        <ul>
            <li>Degree in Construction Management, Civil Engineering, or a related field, or equivalent field experience.</li>
            <li>Proficiency with spreadsheets, email, and other software used in the construction industry.</li>
            <li>The ability to read and understand blueprint drawings.</li>
            <li>The ability to effectively communicate both in written and spoken English.</li>
        </ul>

